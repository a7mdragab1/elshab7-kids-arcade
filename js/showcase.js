function renderGallerySlide() {
  const g = GAMES[galGameId] || GAMES.smart_kids;
  const total = g.shots.length;
  galSlide = ((galSlide % total) + total) % total;
  const current = g.shots[galSlide];

  galIcon.src = g.icon;
  galIcon.alt = `${g.title} icon`;
  galTitle.textContent = g.title;
  galStore.href = g.storeUrl;
  galStore.setAttribute('aria-label', `Get ${g.title} on Google Play`);
  galMainImg.src = current.src;
  galMainImg.alt = current.caption;
  galCaption.textContent = current.caption;
  galCounter.textContent = `${galSlide + 1} / ${total}`;

  galThumbs.innerHTML = g.shots.map((shot, idx) => `
    <button type="button" class="lb-thumb" data-gal-idx="${idx}" data-active="${idx === galSlide}" aria-label="Show screenshot ${idx + 1}">
      <img src="${shot.src}" referrerpolicy="no-referrer" alt="">
    </button>
  `).join('');

  galThumbs.querySelectorAll('.lb-thumb').forEach((tb) => {
    tb.addEventListener('click', () => {
      galSlide = Number(tb.dataset.galIdx);
      renderGallerySlide();
      announce(`Screenshot ${galSlide + 1} of ${total}: ${GAMES[galGameId].shots[galSlide].caption}`, true);
    });
  });
}

function openGallery(gameId, slideIdx = 0, trigger = null) {
  lastTrigger = trigger || document.activeElement;
  galGameId = GAMES[gameId] ? gameId : 'smart_kids';
  galSlide = Number(slideIdx) || 0;
  dialog.removeAttribute('data-closing');
  renderGallerySlide();
  if (!dialog.open) dialog.showModal();
  galTitle.focus();
  announce(`Opened gallery for ${GAMES[galGameId].title}`, true);
}

galPrev.addEventListener('click', () => {
  galSlide -= 1;
  renderGallerySlide();
  announce(GAMES[galGameId].shots[galSlide].caption, true);
});

galNext.addEventListener('click', () => {
  galSlide += 1;
  renderGallerySlide();
  announce(GAMES[galGameId].shots[galSlide].caption, true);
});

dialog.addEventListener('keydown', (e) => {
  if (!dialog.open) return;
  if (e.key === 'ArrowLeft') { e.preventDefault(); galPrev.click(); }
  if (e.key === 'ArrowRight') { e.preventDefault(); galNext.click(); }
});

document.addEventListener('click', (e) => {
  const trigger = e.target.closest('[data-open-gallery]');
  if (!trigger) return;
  openGallery(trigger.dataset.openGallery, trigger.dataset.slide || 0, trigger);
});

// IntersectionObserver Scroll Reveal Fallback
if (!CSS.supports('(animation-timeline: view()) and (animation-range: entry)') &&
    !motionPaused &&
    'IntersectionObserver' in window) {
  const cards = document.querySelectorAll('.reveal-card');
  cards.forEach((c) => c.classList.add('reveal-hidden'));
  const obs = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.remove('reveal-hidden');
        entry.target.classList.add('reveal-visible');
        obs.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1 });
  cards.forEach((c) => obs.observe(c));
}

